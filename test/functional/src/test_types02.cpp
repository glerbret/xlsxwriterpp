#include "xlsxwriterpp.h"

int main()
{
  xwpp::workbook_t workbook;
  xwpp::worksheet_t& worksheet = workbook.add_worksheet();

  worksheet.write_boolean(CELL("A1"), true);
  worksheet.write_boolean(CELL("A2"), false);

  workbook.save("test_types02.xlsx");
}
