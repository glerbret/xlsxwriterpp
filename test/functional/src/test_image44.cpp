#include "xlsxwriterpp.h"

int main()
{
  xwpp::workbook_t workbook;
  xwpp::worksheet_t& worksheet = workbook.add_worksheet();

  worksheet.insert_image(CELL("E9"), "images/red.png");

  worksheet.set_row(8, 30);

  workbook.save("test_image44.xlsx");
}
